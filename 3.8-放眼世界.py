city = ["Tokyo","London","NewYork","Norway","Moscow"]
print(city)
print(sorted(city))#sorted 是一个函数而不是一个方法
print(city)
print(sorted(city,reverse=True))
print(city)
city.reverse()#reverse() 是一个方法
print(city)
city.reverse()#reverse() 是一个方法
print(city)
city.sort()#sort() 是一个方法
print(city)
city.sort(reverse=True)
print(city)